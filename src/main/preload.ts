import { contextBridge, ipcRenderer, webUtils } from 'electron';

contextBridge.exposeInMainWorld('mockupApi', {
  carregarPacote: (nome?: string) => ipcRenderer.invoke('carregar-pacote', nome),
  escolherPdf: (pastaInicial?: string) => ipcRenderer.invoke('escolher-pdf', pastaInicial),
  lerPdf: (caminho: string) => ipcRenderer.invoke('ler-pdf', caminho),
  caminhoDoArquivo: (arquivo: File) => webUtils.getPathForFile(arquivo),
  prepararMkp: (caminhoDoPdf: string) => ipcRenderer.invoke('preparar-mkp', caminhoDoPdf),
  versao: () => ipcRenderer.invoke('versao'),
  operador: () => ipcRenderer.invoke('operador'),
  listarHistorico: () => ipcRenderer.invoke('historico-listar'),
  salvarNoHistorico: (e: unknown) => ipcRenderer.invoke('historico-salvar', e),
  removerDoHistorico: (id: string) => ipcRenderer.invoke('historico-remover', id),
  listarRascunhos: () => ipcRenderer.invoke('rascunhos-listar'),
  salvarRascunho: (r: unknown) => ipcRenderer.invoke('rascunhos-salvar', r),
  removerRascunho: (caminho: string) => ipcRenderer.invoke('rascunhos-remover', caminho),
  designerEstado: () => ipcRenderer.invoke('designer-estado'),
  fluxoConferido: (caminho: string) => ipcRenderer.invoke('fluxo-conferido', caminho),
  ocupado: (ocupado: boolean) => ipcRenderer.invoke('ocupado', ocupado),
  fluxoVoltouVisto: (caminho: string) => ipcRenderer.invoke('fluxo-voltou-visto', caminho),
  salvarTemporario: (nome: string, bytes: Uint8Array) => ipcRenderer.invoke('salvar-temporario', nome, bytes),
  corelArteNoMolde: (entrada: { frente?: string; verso?: string; destino: string; copiar?: string }) => ipcRenderer.invoke('corel-arte-no-molde', entrada),
  corelGerarPdf: (caminho: string) => ipcRenderer.invoke('corel-gerar-pdf', caminho),
  notificacaoTestar: () => ipcRenderer.invoke('notificacao-testar'),
  designerProcurarPastas: (substituir: boolean) => ipcRenderer.invoke('designer-procurar-pastas', substituir),
  designerLigar: (ligado: boolean, pin?: string) => ipcRenderer.invoke('designer-ligar', ligado, pin),
  designerEscolherPasta: (qual: 'pasta1' | 'pasta2' | 'pasta3' | 'pasta4') => ipcRenderer.invoke('designer-escolher-pasta', qual),
  anunciosPastas: () => ipcRenderer.invoke('anuncios-pastas'),
  anunciosCategorias: (plataforma: string) => ipcRenderer.invoke('anuncios-categorias', plataforma),
  anunciosCriarCategoria: (plataforma: string, nome: string) => ipcRenderer.invoke('anuncios-criar-categoria', plataforma, nome),
  anunciosAbrirPasta: (caminho: string) => ipcRenderer.invoke('anuncios-abrir-pasta', caminho),
  anunciosCriar: (entrada: unknown, montarNoCorel: boolean) => ipcRenderer.invoke('anuncios-criar', entrada, montarNoCorel),
  iniciarComWindowsEstado: () => ipcRenderer.invoke('iniciar-windows-estado'),
  iniciarComWindows: (ligado: boolean) => ipcRenderer.invoke('iniciar-windows-definir', ligado),
  abrirArquivoCliente: (caminho: string) => ipcRenderer.invoke('abrir-arquivo-cliente', caminho),
  clientesListar: () => ipcRenderer.invoke('clientes-listar'),
  clientesBuscar: (termo: string) => ipcRenderer.invoke('clientes-buscar', termo),
  aoArteParaFazer: (cb: (nomes: string[]) => void) => ipcRenderer.on('arte-para-fazer', (_e, nomes: string[]) => cb(nomes)),
  aoAbrirCliente: (cb: () => void) => ipcRenderer.on('abrir-cliente', () => cb()),
  fluxoAvancar: (caminho: string) => ipcRenderer.invoke('fluxo-avancar', caminho),
  fluxoMover: (caminho: string) => ipcRenderer.invoke('fluxo-mover', caminho),
  estadoAtualizacao: () => ipcRenderer.invoke('estado-atualizacao'),
  verificarAtualizacao: () => ipcRenderer.invoke('verificar-atualizacao'),
  instalarAtualizacao: () => ipcRenderer.invoke('instalar-atualizacao'),
  aoMudarAtualizacao: (cb: (estado: unknown) => void) => {
    ipcRenderer.on('atualizacao', (_e, estado) => cb(estado));
  },
  existe: (c: string) => ipcRenderer.invoke('existe', c),
  gravarArquivo: (c: string, b: Uint8Array) => ipcRenderer.invoke('gravar-arquivo', c, b),
  renomearArquivo: (de: string, para: string) => ipcRenderer.invoke('renomear-arquivo', de, para),
  removerArquivo: (c: string) => ipcRenderer.invoke('remover-arquivo', c),
  confirmarSobrescrever: (a: string[]) => ipcRenderer.invoke('confirmar-sobrescrever', a),
});
